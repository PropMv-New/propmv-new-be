const PRIORITY = Object.freeze({
  HIGH: 1,
  NORMAL: 5,
  LOW: 10,
});

function queueForJobType(jobType) {
  const type = String(jobType || '');
  if (type.startsWith('EMAIL_')) return QUEUE_NAMES.EMAIL;
  if (type.startsWith('NOTIFY_')) return QUEUE_NAMES.NOTIFICATION;
  if (type.startsWith('INVOICE_')) return QUEUE_NAMES.INVOICE;
  if (type.startsWith('MAINTENANCE_')) return QUEUE_NAMES.MAINTENANCE;
  if (type.startsWith('REPORT_')) return QUEUE_NAMES.REPORT;
  return QUEUE_NAMES.EMAIL;
}

